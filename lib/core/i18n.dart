  static String t(
    BuildContext context,
    String key, {
    Map<String, String>? params,
  }) {
    final code = Localizations.localeOf(context).languageCode;
    return tByCode(code, key, params: params);
  }

  static String tByCode(
    String code,
    String key, {
    Map<String, String>? params,
  }) {
    var value = _dict[code]?[key] ?? _dict['id']?[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }

  static String translateCategory(BuildContext context, String raw) {
    const idToKey = <String, String>{
      'Makan': 'cat_food',
      'Transport': 'cat_transport',
      'Belanja': 'cat_shopping',
      'Kesehatan': 'cat_health',
      'Hiburan': 'cat_entertainment',
      'Lainnya': 'cat_others',
      'Gaji': 'cat_salary',
      'Freelance': 'cat_freelance',
      'Bisnis': 'cat_business',
      'Investasi': 'cat_investment',
    };
    final key = idToKey[raw];
    if (key == null) return raw;
    return t(context, key);
  }

  static String translateRelativeDate(BuildContext context, String raw) {
    var value = raw;
    value = value.replaceAll('Hari ini', t(context, 'today'));
    value = value.replaceAll('Besok', t(context, 'tomorrow'));
    value = value.replaceAll('Kemarin', t(context, 'yesterday'));
    value = value.replaceAll('Today', t(context, 'today'));
    value = value.replaceAll('Tomorrow', t(context, 'tomorrow'));
    value = value.replaceAll('Yesterday', t(context, 'yesterday'));
    return value;
  }

  static String translateDebtTitle(BuildContext context, String raw) {
    final code = Localizations.localeOf(context).languageCode;
    if (code != 'en') {
      return raw;
    }
    if (raw.startsWith('Utang ')) return raw.replaceFirst('Utang ', 'Debt ');
    if (raw.startsWith('Piutang ')) {
      return raw.replaceFirst('Piutang ', 'Receivable ');
    }
    return raw;
  }
